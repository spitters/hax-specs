/// Encrypt the vector's payload and compare header || ciphertext || tag with
/// the RFC output, then decrypt and compare with the payload.
fn check(v: &Vector) {
    let aad_bytes = &v.packet[..v.hdr_len];
    let pt_bytes = &v.packet[v.hdr_len..];
    let pt_len = pt_bytes.len();
    let tag_len = v.expected.len() - v.packet.len();
    assert!(tag_len == 8 || tag_len == 10, "#{}: tag length {}", v.id, tag_len);
    assert_eq!(&v.expected[..v.hdr_len], aad_bytes, "#{}: header echoed", v.id);

    let mut plaintext = [0u8; MAX_MSG];
    plaintext[..pt_len].copy_from_slice(pt_bytes);
    let mut aad = [0u8; MAX_AAD];
    aad[..v.hdr_len].copy_from_slice(aad_bytes);

    let (ct, tag) =
        ccm_encrypt(&v.key, &v.nonce, 13, &plaintext, pt_len, &aad, v.hdr_len, tag_len);

    let expected_ct = &v.expected[v.hdr_len..v.packet.len()];
    let expected_tag = &v.expected[v.packet.len()..];
    assert_eq!(&ct[..pt_len], expected_ct, "#{}: ciphertext", v.id);
    assert_eq!(&tag[..tag_len], expected_tag, "#{}: tag", v.id);

    let mut recv_tag = [0u8; 16];
    recv_tag[..tag_len].copy_from_slice(expected_tag);
    let recovered =
        ccm_decrypt(&v.key, &v.nonce, 13, &ct, pt_len, &aad, v.hdr_len, &recv_tag, tag_len)
            .unwrap_or_else(|| panic!("#{}: decrypt rejected valid tag", v.id));
    assert_eq!(&recovered[..pt_len], pt_bytes, "#{}: recovered plaintext", v.id);

    // A single flipped ciphertext bit must be rejected.
    let mut tampered = ct;
    tampered[0] ^= 0x01;
    assert!(
        ccm_decrypt(&v.key, &v.nonce, 13, &tampered, pt_len, &aad, v.hdr_len, &recv_tag, tag_len)
            .is_none(),
        "#{}: tampered ciphertext accepted",
        v.id
    );
}

#[test]
fn kat_rfc3610_vectors_5_to_12() {
    for v in &VECTORS[..8] {
        check(v);
    }
}

#[test]
fn kat_rfc3610_vectors_13_to_24() {
    for v in &VECTORS[8..] {
        check(v);
    }
}
