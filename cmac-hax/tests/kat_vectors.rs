// ============================================================
// dbl (GF(2^128) doubling) — algebraic properties
// ============================================================

#[test]
fn kat_dbl_sp800_38b() {
    // L from SP 800-38B D.1
    let l: Block = [
        0x7d, 0xf7, 0x6b, 0x0c, 0x1a, 0xb8, 0x99, 0xb3,
        0x3e, 0x42, 0xf0, 0x47, 0xb9, 0x1b, 0x54, 0x6f,
    ];
    let k1 = dbl(&l);
    let expected_k1: Block = [
        0xfb, 0xee, 0xd6, 0x18, 0x35, 0x71, 0x33, 0x66,
        0x7c, 0x85, 0xe0, 0x8f, 0x72, 0x36, 0xa8, 0xde,
    ];
    assert_eq!(k1, expected_k1, "dbl(L) should match K1");
}

#[test]
fn kat_dbl_zero() {
    assert_eq!(dbl(&ZERO_BLOCK), ZERO_BLOCK, "dbl(0) = 0");
}

